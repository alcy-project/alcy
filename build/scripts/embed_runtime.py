"""Embeds the program runtime sources as byte arrays.

Reads runtime/alcy_runtime.h and runtime/alcy_runtime.c, emitting a
translation unit that exposes their exact bytes. Object embedding via
objcopy is intentionally avoided: byte arrays are portable across
every host without external tools or per-architecture handling.
"""

import argparse
from pathlib import Path


def emit_array(out, symbol, data: bytes):
    out.write(f"const unsigned char {symbol}[] = {{\n")
    for offset in range(0, len(data), 12):
        chunk = data[offset : offset + 12]
        out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n")
    out.write(f"const u64 {symbol}_len = {len(data)}ULL;\n\n")


def main():
    parser = argparse.ArgumentParser(description="Embed runtime sources.")
    parser.add_argument("--runtime-dir", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    runtime_dir = Path(args.runtime_dir)
    files = {
        "kAlcyRuntimeHeader": runtime_dir / "alcy_runtime.h",
        "kAlcyRuntimeSource": runtime_dir / "alcy_runtime.c",
    }
    with open(args.output, "w", encoding="utf-8") as out:
        out.write(
            "// Copyright 2026 The Alcy Project Authors\n"
            "// This source code is licensed under the Apache License, "
            "Version 2.0 with LLVM\n"
            "// Exceptions which can be found in the LICENSE file.\n"
            "\n"
            "// Generated by build/scripts/embed_runtime.py; do not edit.\n"
            "\n"
            '#include "app/embedded_runtime.h"\n'
            "\n"
            '#include "fpag/base/numeric.h"\n'
            "\n"
            "namespace app {\n"
            "\n"
        )
        for symbol, path in files.items():
            emit_array(out, symbol, path.read_bytes())
        out.write("}  // namespace app\n")


if __name__ == "__main__":
    main()
