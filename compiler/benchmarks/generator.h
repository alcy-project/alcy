#pragma once

#include <string>
#include <string_view>

#include "fpag/base/numeric.h"

namespace bench {

// The three dimensions a generated source varies. Cost grows along each,
// and they are independent so a case can hold two fixed and move one.
//
// Module count is not among them: varying it needs a manifest, which
// puts the filesystem back into the measured path. That belongs to the
// process runner.
struct SourceSpec {
  u32 functions = 64;
  u32 statements = 8;
  u32 depth = 3;
};

// A source built from `spec`. Deterministic: the same spec always yields
// the same bytes, so a case is repeatable and its result attributable.
std::string generate_source(SourceSpec spec);

// A short digest of the generated bytes, recorded with every result.
// Two runs are comparable only if these agree.
std::string source_digest(std::string_view source);

}  // namespace bench
